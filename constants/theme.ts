function hexToHsl(hex: string): [number, number, number] {
  const c = hex.replace('#', '');
  const r = parseInt(c.substring(0, 2), 16) / 255;
  const g = parseInt(c.substring(2, 4), 16) / 255;
  const b = parseInt(c.substring(4, 6), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const sat = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h = 0;
  if (max === r)      h = (g - b) / d + (g < b ? 6 : 0);
  else if (max === g) h = (b - r) / d + 2;
  else                h = (r - g) / d + 4;
  return [h * 60, sat, l];
}

function hslToHex(h: number, sat: number, l: number): string {
  const k = (n: number) => (n + h / 30) % 12;
  const a = sat * Math.min(l, 1 - l);
  const f = (n: number) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  const to = (x: number) => Math.round(x * 255).toString(16).padStart(2, '0').toUpperCase();
  return `#${to(f(0))}${to(f(8))}${to(f(4))}`;
}

/**
 * The dark-scheme twin of a light colour: lighter, so it reads on a dark ground, and at ~80% of
 * its saturation, so it does not glow. A neutral (a grey accent like Graphite's) goes near-white
 * instead — the point of a neutral accent is that it is the brightest thing on the screen.
 */
export function toDarkVariant(hex: string): string {
  const [h, sat, l] = hexToHsl(hex);
  if (sat < 0.15) return hslToHex(h, sat, 0.9);
  return hslToHex(h, sat * 0.8, Math.max(l, 0.68));
}

