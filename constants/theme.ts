/**
 * The palette as it is written down: surfaces, accents and semantic colours only.
 * Foregrounds are deliberately absent — see `ThemeColors` below.
 *
 * Surfaces are three tones, not shadows (W2-20/W2-22): `background` is the page, `card` sits on
 * it, `cardAlt` sits on a card (chips, badges, the pressed state). In dark they step *up* in
 * lightness so elevation stays legible where a shadow is invisible; in light they step down and
 * a hairline border does the rest. `surface`, `inputBg` and `separator` are aliases onto those
 * three so nothing has a fourth tone to drift to.
 */
